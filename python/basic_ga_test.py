"""
Basic Genetic Algorithm Demonstration using DEAP.

This module illustrates how to separate and structure:
1. Gene variable types and value boundaries (ranges).
2. Individual generators (how individuals/chromosomes are built).
3. GA hyperparameters (population size, generations, crossover, mutation, selection).
"""

import random
from dataclasses import dataclass
from typing import Callable, Tuple
from deap import algorithms, base, creator, tools


# ==============================================================================
# 1. CONFIGURATION STRUCTURES
# ==============================================================================

@dataclass
class GeneConfig:
    """Configuration defining each gene (variable type and allowed range)."""
    # Type description: 'int' or 'float'
    gene_type: str
    # Lower bound of the gene value range (inclusive)
    min_value: int
    # Upper bound of the gene value range (inclusive)
    max_value: int
    # Total number of genes in each individual (chromosome length)
    chromosome_length: int


@dataclass
class GAConfig:
    """Genetic Algorithm hyperparameters."""
    # Number of individuals in the population
    population_size: int = 50
    # Number of generations (evolution iterations)
    generations: int = 40
    # Crossover probability: chance of mating two selected parent individuals
    crossover_prob: float = 0.5
    # Mutation probability: chance that an individual undergoes mutation
    individual_mutation_prob: float = 0.2
    # Gene mutation probability: probability for each independent gene to mutate
    gene_mutation_prob: float = 0.2
    # Tournament size: number of individuals competing in tournament selection
    tournament_size: int = 3


# ==============================================================================
# 2. TOOLBOX BUILDER (SEPARATED & STRUCTURED GA COMPONENTS)
# ==============================================================================

def build_ga_toolbox(
    individual_cls: type,
    gene_cfg: GeneConfig,
    ga_cfg: GAConfig,
    eval_function: Callable[[list], Tuple[float, ...]],
) -> base.Toolbox:
    """
    Builds and configures the DEAP Toolbox.
    
    Here we explicitly separate:
    - (A) Gene Attribute Generator (variable type & range definition)
    - (B) Individual Generator (how an individual is created)
    - (C) Population Generator (collection of individuals)
    - (D) Genetic Operators (evaluation, selection, crossover, mutation)
    """
    toolbox = base.Toolbox()

    # --------------------------------------------------------------------------
    # (A) GENE DEFINITION (Variable Type & Value Range)
    # --------------------------------------------------------------------------
    if gene_cfg.gene_type == "int":
        # Generates an integer uniformly distributed in [min_value, max_value]
        toolbox.register(
            "attr_gene",
            random.randint,
            gene_cfg.min_value,
            gene_cfg.max_value,
        )
    elif gene_cfg.gene_type == "float":
        # Generates a floating-point number uniformly distributed in [min_value, max_value]
        toolbox.register(
            "attr_gene",
            random.uniform,
            gene_cfg.min_value,
            gene_cfg.max_value,
        )
    else:
        raise ValueError(f"Unsupported gene type: {gene_cfg.gene_type}")

    # --------------------------------------------------------------------------
    # (B) INDIVIDUAL GENERATOR
    # --------------------------------------------------------------------------
    # Defines how an individual is created:
    # Uses tools.initRepeat to repeatedly call 'attr_gene' (n = chromosome_length times)
    # and populates an instance of individual_cls.
    toolbox.register(
        "individual",
        tools.initRepeat,
        individual_cls,
        toolbox.attr_gene,
        n=gene_cfg.chromosome_length,
    )

    # --------------------------------------------------------------------------
    # (C) POPULATION GENERATOR
    # --------------------------------------------------------------------------
    # Creates a list of individuals generated by toolbox.individual
    toolbox.register(
        "population",
        tools.initRepeat,
        list,
        toolbox.individual,
    )

    # --------------------------------------------------------------------------
    # (D) GENETIC OPERATORS
    # --------------------------------------------------------------------------
    # 1. Evaluation function: measures fitness score of an individual
    toolbox.register("evaluate", eval_function)

    # 2. Crossover operator: two-point crossover exchanges segments between parents
    toolbox.register("mate", tools.cxTwoPoint)

    # 3. Mutation operator: alters genes according to the defined type and range
    if gene_cfg.gene_type == "int":
        toolbox.register(
            "mutate",
            tools.mutUniformInt,
            low=gene_cfg.min_value,
            up=gene_cfg.max_value,
            indpb=ga_cfg.gene_mutation_prob,
        )
    else:
        toolbox.register(
            "mutate",
            tools.mutGaussian,
            mu=0.0,
            sigma=1.0,
            indpb=ga_cfg.gene_mutation_prob,
        )

    # 4. Selection operator: tournament selection picks best candidate out of k random candidates
    toolbox.register(
        "select",
        tools.selTournament,
        tournsize=ga_cfg.tournament_size,
    )

    return toolbox


# ==============================================================================
# 3. EXPERIMENTS
# ==============================================================================

def run_sum_of_two_numbers_ga(gene_cfg: GeneConfig, ga_cfg: GAConfig):
    """Experiment 1: Maximize the sum of 2 numbers."""
    print("=" * 60)
    print("EXPERIMENT 1: Maximize sum of 2 numbers")
    print(f"Gene Type: {gene_cfg.gene_type} | Range: [{gene_cfg.min_value}, {gene_cfg.max_value}] | Length: {gene_cfg.chromosome_length}")
    print("=" * 60)

    # 1. Create fitness and individual types for Maximization (weight = +1.0)
    if not hasattr(creator, "FitnessMax"):
        creator.create("FitnessMax", base.Fitness, weights=(1.0,))
    if not hasattr(creator, "IndividualTwo"):
        creator.create("IndividualTwo", list, fitness=creator.FitnessMax)

    # 2. Objective function: maximize the sum of elements
    def eval_sum_two(individual):
        return (sum(individual),)

    # 3. Build configured toolbox
    toolbox = build_ga_toolbox(
        individual_cls=creator.IndividualTwo,
        gene_cfg=gene_cfg,
        ga_cfg=ga_cfg,
        eval_function=eval_sum_two,
    )

    # 4. Initialize population and Hall of Fame (stores best individual found)
    population = toolbox.population(n=ga_cfg.population_size)
    hof = tools.HallOfFame(1)

    # 5. Execute Simple Evolutionary Algorithm
    algorithms.eaSimple(
        population=population,
        toolbox=toolbox,
        cxpb=ga_cfg.crossover_prob,
        mutpb=ga_cfg.individual_mutation_prob,
        ngen=ga_cfg.generations,
        halloffame=hof,
        verbose=False,
    )

    best_individual = hof[0]
    print(f"Generations: {ga_cfg.generations} | Population size: {ga_cfg.population_size}")
    print(f"Best Individual ({gene_cfg.chromosome_length} genes): {best_individual}")
    print(f"Fitness (Max Sum): {best_individual.fitness.values[0]}")
    print()


